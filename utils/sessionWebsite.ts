/**
 * Offline "session → website" generator.
 *
 * Builds a complete, self-contained HTML page from a session's sources.
 * Pure string building only — no AI call, no API key, no network requests.
 * The generated page uses inline CSS exclusively (no <link>, no <script src>,
 * no web fonts, no CDN), so it works anywhere as a single file.
 *
 * Source handling:
 * - text / document / sql / html → page sections (base64-decoded, HTML-escaped)
 * - image → embedded via data: URL
 * - link → resource card (http/https hrefs only)
 * - pdf / video / audio → listed cards (not embedded, keeps the page light)
 * - recent chat → "Conversation highlights" section
 *
 * Input selection: only the session's *selected* sources are used when a
 * selection exists, otherwise all sources. Previously generated
 * `Website: …` HTML sources are always excluded so a website never nests
 * inside itself.
 */
import type { MediaItem, Session } from '../types';

export const SESSION_WEBSITE_PREFIX = 'Website: ';
export const DEFAULT_MAX_CHAT_MESSAGES = 8;
export const DEFAULT_MAX_TEXT_CHARS = 12000;
export const DEFAULT_MAX_CHAT_CHARS = 2000;

export interface SessionWebsiteOptions {
  /** How many recent chat messages to include (default 8). */
  maxChatMessages?: number;
  /** Max characters of decoded text kept per text-like source (default 12000). */
  maxTextChars?: number;
  /** Max characters kept per chat message (default 2000). */
  maxChatChars?: number;
  /** Override for the "Generated …" timestamp (useful for tests). */
  generatedAt?: Date | number;
}

/** Escape a string for safe interpolation into HTML text/attribute context. */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Decode a base64-encoded text payload (UTF-8) to a string.
 * Falls back to the raw value when it is not valid base64 (e.g. plain text),
 * and to an empty string when decoding fails.
 */
export function decodeBase64Text(data: string): string {
  if (!data) return '';
  const trimmed = data.trim();
  // Plain-text payloads (e.g. link URLs stored verbatim) are not base64.
  if (!/^[A-Za-z0-9+/=\s]+$/.test(trimmed) || trimmed.replace(/\s/g, '').length % 4 !== 0) {
    return data;
  }
  try {
    const binary = atob(trimmed.replace(/\s/g, ''));
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
    return new TextDecoder().decode(bytes);
  } catch {
    return data;
  }
}

/** True for HTML sources previously generated by this module. */
export function isGeneratedWebsiteSource(item: MediaItem): boolean {
  return item.type === 'html' && item.name.startsWith(SESSION_WEBSITE_PREFIX);
}

/**
 * Pick the sources to render: the session's selected sources when a
 * selection exists, otherwise all sources. Generated `Website: …`
 * sources are excluded to avoid nesting a previous website inside itself.
 */
export function getSessionWebsiteSources(session: Session): MediaItem[] {
  const all = session.mediaItems ?? [];
  const selectedIds = session.selectedMediaIds ?? [];
  const pool = selectedIds.length > 0
    ? all.filter((item) => selectedIds.includes(item.id))
    : all;
  return pool.filter((item) => !isGeneratedWebsiteSource(item));
}

/** Slugify a session name for use in a filename (`Research 001` → `research_001`). */
export function slugifySessionName(name: string): string {
  const slug = (name || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
  return slug || 'session';
}

/** Download filename for the generated page, e.g. `research_001-website.html`. */
export function sessionWebsiteFilename(session: Session): string {
  return `${slugifySessionName(session.name)}-website.html`;
}

/** Name of the HTML source the page is saved back into the session as. */
export function sessionWebsiteSourceName(session: Session): string {
  const name = (session.name || '').trim() || 'Untitled session';
  return `${SESSION_WEBSITE_PREFIX}${name}`;
}

/** Build a data: URL for a binary source (tolerates already-prefixed data). */
export function toDataUrl(item: MediaItem): string {
  if (item.data.startsWith('data:')) return item.data;
  const mime = item.mimeType || 'application/octet-stream';
  return `data:${mime};base64,${item.data}`;
}

/** Approximate decoded byte size of a base64 payload. */
export function approxBytesFromBase64(data: string): number {
  if (!data || data.startsWith('data:')) return data ? data.length : 0;
  return Math.floor((data.length * 3) / 4);
}

export function formatBytes(bytes: number): string {
  if (!Number.isFinite(bytes) || bytes <= 0) return '0 B';
  const units = ['B', 'KB', 'MB', 'GB'];
  const i = Math.min(units.length - 1, Math.floor(Math.log(bytes) / Math.log(1024)));
  const value = bytes / Math.pow(1024, i);
  return `${value >= 10 || i === 0 ? Math.round(value) : value.toFixed(1)} ${units[i]}`;
}

/** Only http(s) URLs may become clickable links (blocks `javascript:` etc.). */
export function safeHttpUrl(value: string): string | null {
  const trimmed = (value || '').trim();
  try {
    const url = new URL(trimmed);
    return url.protocol === 'http:' || url.protocol === 'https:' ? url.href : null;
  } catch {
    return null;
  }
}

function truncate(text: string, maxChars: number): { text: string; truncated: boolean } {
  if (text.length <= maxChars) return { text, truncated: false };
  return { text: text.slice(0, maxChars), truncated: true };
}

function sectionId(index: number, name: string): string {
  const slug = slugifySessionName(name).slice(0, 40) || 'source';
  return `src-${index + 1}-${slug}`;
}

const TYPE_LABELS: Record<MediaItem['type'], string> = {
  text: 'Text',
  document: 'Document',
  sql: 'SQL',
  html: 'HTML',
  image: 'Image',
  link: 'Link',
  pdf: 'PDF',
  video: 'Video',
  audio: 'Audio',
};

const TYPE_ICONS: Record<MediaItem['type'], string> = {
  text: '📝',
  document: '📄',
  sql: '🗄️',
  html: '🌐',
  image: '🖼️',
  link: '🔗',
  pdf: '📕',
  video: '🎬',
  audio: '🎵',
};

function renderTextSection(item: MediaItem, id: string, maxTextChars: number): string {
  const decoded = decodeBase64Text(item.data);
  const { text, truncated } = truncate(decoded, maxTextChars);
  const note = truncated
    ? `<p class="truncated">… truncated — showing the first ${maxTextChars.toLocaleString()} of ${decoded.length.toLocaleString()} characters.</p>`
    : '';
  if (item.type === 'sql' || item.type === 'html') {
    const hint = item.type === 'html'
      ? '<p class="hint">HTML source shown as code (escaped, not executed).</p>'
      : '';
    return `<section id="${id}" class="section"><h2>${TYPE_ICONS[item.type]} ${escapeHtml(item.name)}</h2><p class="meta">${TYPE_LABELS[item.type]} · ${escapeHtml(item.mimeType || 'text/plain')}</p>${hint}<pre class="code"><code>${escapeHtml(text)}</code></pre>${note}</section>`;
  }
  return `<section id="${id}" class="section"><h2>${TYPE_ICONS[item.type]} ${escapeHtml(item.name)}</h2><p class="meta">${TYPE_LABELS[item.type]} · ${escapeHtml(item.mimeType || 'text/plain')}</p><div class="text-body">${escapeHtml(text)}</div>${note}</section>`;
}

function renderImageSection(item: MediaItem, id: string): string {
  const size = formatBytes(approxBytesFromBase64(item.data));
  const body = item.data
    ? `<figure class="image-figure"><img src="${escapeHtml(toDataUrl(item))}" alt="${escapeHtml(item.name)}" loading="lazy" /><figcaption>${escapeHtml(item.name)} · ${escapeHtml(item.mimeType || 'image')} · ${size} · embedded</figcaption></figure>`
    : `<div class="card"><span class="card-icon">🖼️</span><div><strong>${escapeHtml(item.name)}</strong><p class="meta">Image with no data stored.</p></div></div>`;
  return `<section id="${id}" class="section"><h2>${TYPE_ICONS.image} ${escapeHtml(item.name)}</h2>${body}</section>`;
}

function renderLinkSection(item: MediaItem, id: string): string {
  const rawUrl = (item.data || '').trim();
  const url = safeHttpUrl(rawUrl) || safeHttpUrl(item.name);
  const title = url && item.name !== url ? item.name : (url || item.name);
  const body = url
    ? `<div class="card link-card"><span class="card-icon">🔗</span><div class="card-body"><a href="${escapeHtml(url)}" target="_blank" rel="noopener noreferrer">${escapeHtml(title)}</a><p class="meta url">${escapeHtml(url)}</p></div></div>`
    : `<div class="card"><span class="card-icon">🔗</span><div class="card-body"><strong>${escapeHtml(item.name)}</strong><p class="meta">Link (not a valid http/https URL, shown as text).</p></div></div>`;
  return `<section id="${id}" class="section"><h2>${TYPE_ICONS.link} ${escapeHtml(title)}</h2>${body}</section>`;
}

function renderBinaryCardSection(item: MediaItem, id: string): string {
  const size = formatBytes(approxBytesFromBase64(item.data));
  return `<section id="${id}" class="section"><h2>${TYPE_ICONS[item.type]} ${escapeHtml(item.name)}</h2><div class="card"><span class="card-icon">${TYPE_ICONS[item.type]}</span><div class="card-body"><strong>${escapeHtml(item.name)}</strong><p class="meta">${TYPE_LABELS[item.type]} · ${escapeHtml(item.mimeType || 'unknown type')} · ${size}</p><p class="hint">Binary file — listed here, not embedded. Open the original source in Aggi to view or play it.</p></div></div></section>`;
}

function renderSourceSection(item: MediaItem, index: number, maxTextChars: number): string {
  const id = sectionId(index, item.name);
  switch (item.type) {
    case 'text':
    case 'document':
    case 'sql':
    case 'html':
      return renderTextSection(item, id, maxTextChars);
    case 'image':
      return renderImageSection(item, id);
    case 'link':
      return renderLinkSection(item, id);
    case 'pdf':
    case 'video':
    case 'audio':
      return renderBinaryCardSection(item, id);
    default:
      return renderBinaryCardSection(item, id);
  }
}

function renderConversationSection(session: Session, maxChatMessages: number, maxChatChars: number): string {
  const history = (session.history ?? []).filter((m) => m && typeof m.content === 'string' && m.content.trim());
  if (history.length === 0) return '';
  const recent = history.slice(-Math.max(0, maxChatMessages));
  if (recent.length === 0) return '';
  const messages = recent.map((msg) => {
    const { text, truncated } = truncate(msg.content, maxChatChars);
    const roleLabel = msg.role === 'user' ? 'You' : 'Assistant';
    const when = msg.timestamp ? new Date(msg.timestamp).toLocaleString() : '';
    const note = truncated ? '<p class="truncated">… truncated.</p>' : '';
    return `<article class="msg ${escapeHtml(msg.role)}"><header><span class="role">${roleLabel}</span>${when ? `<time>${escapeHtml(when)}</time>` : ''}</header><div class="msg-body">${escapeHtml(text)}</div>${note}</article>`;
  }).join('\n');
  return `<section id="conversation" class="section"><h2>💬 Conversation highlights</h2><p class="meta">Latest ${recent.length} of ${history.length} message${history.length === 1 ? '' : 's'}</p><div class="chat">${messages}</div></section>`;
}

