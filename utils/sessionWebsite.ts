/**
 * Build the complete, self-contained HTML page for a session.
 * No AI call, no API key, no external requests — pure local string building.
 */
export function buildSessionWebsiteHtml(session: Session, options: SessionWebsiteOptions = {}): string {
  const maxChatMessages = options.maxChatMessages ?? DEFAULT_MAX_CHAT_MESSAGES;
  const maxTextChars = options.maxTextChars ?? DEFAULT_MAX_TEXT_CHARS;
  const maxChatChars = options.maxChatChars ?? DEFAULT_MAX_CHAT_CHARS;
  const generatedAt = options.generatedAt ? new Date(options.generatedAt) : new Date();

  const title = (session.name || '').trim() || 'Untitled session';
  const sources = getSessionWebsiteSources(session);
  const hasSelection = (session.selectedMediaIds ?? []).length > 0 && sources.length > 0;
  const created = session.createdAt ? new Date(session.createdAt).toLocaleString() : '';

  const sections = sources.map((item, i) => renderSourceSection(item, i, maxTextChars));
  const conversation = renderConversationSection(session, maxChatMessages, maxChatChars);

  const tocItems = [
    ...sources.map((item, i) => `<li><a href="#${sectionId(i, item.name)}">${escapeHtml(item.name)}</a></li>`),
    ...(conversation ? ['<li><a href="#conversation">Conversation highlights</a></li>'] : []),
  ].join('\n');

  const bodySections = sections.length > 0
    ? sections.join('\n')
    : '<p class="empty">No sources in this session yet — add text, images, links or files and generate again.</p>';

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${escapeHtml(title)} — Website</title>
<style>${PAGE_CSS}</style>
</head>
<body>
<div class="wrap">
<header class="hero">
<h1>${escapeHtml(title)}</h1>
${session.description ? `<p>${escapeHtml(session.description)}</p>` : ''}
<p>${sources.length} source${sources.length === 1 ? '' : 's'}${hasSelection ? ' (selected only)' : ''}${created ? ` · Created ${escapeHtml(created)}` : ''}</p>
</header>
${tocItems ? `<nav class="toc" aria-label="Contents"><strong>Contents</strong><ul>\n${tocItems}\n</ul></nav>` : ''}
${bodySections}
${conversation}
<footer class="page-footer">Generated ${escapeHtml(generatedAt.toLocaleString())} locally from this session — no AI call, no external requests. Single file: save &amp; share anywhere.</footer>
</div>
</body>
</html>`;
}

/**
 * Trigger a browser download of the generated page.
 * No-op outside a DOM environment (e.g. unit tests).
 */
export function downloadSessionWebsiteHtml(html: string, filename: string): void {
  if (typeof document === 'undefined' || typeof URL === 'undefined') return;
  const blob = new Blob([html], { type: 'text/html' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
